// Write the skills into src/core/skill-prompts.ts, so the server offers each one as an MCP prompt (Cloudflare and the
// bundled plugin cannot read skills/ at run time). Run after changing a skill; a test fails while they differ.
import fs from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const root = process.cwd();
const dir = path.join(root, "skills");
const names = (await fs.readdir(dir, { withFileTypes: true })).filter((entry) => entry.isDirectory()).map((entry) => entry.name).sort();
const prompts = [];
for (const name of names) {
  const text = await fs.readFile(path.join(dir, name, "SKILL.md"), "utf8");
  const match = /^---\n([\s\S]*?)\n---\n+([\s\S]*)$/.exec(text.replace(/\r\n/g, "\n"));
  if (!match) throw new Error(`skills/${name}/SKILL.md has no front matter`);
  const field = (key) => new RegExp(`^${key}:\\s*(.+)$`, "m").exec(match[1])?.[1]?.trim();
  if (field("name") !== name) throw new Error(`skills/${name}/SKILL.md names itself ${field("name")}`);
  prompts.push({ name, description: field("description") ?? "", body: match[2].trim() });
}
const out = `// Generated by scripts/build-prompts.mjs from skills/*/SKILL.md. Do not edit; change the skill and run \`pnpm build:prompts\`.

/** Each skill: its name, when to use it, and its steps. */
export const SKILL_PROMPTS: ReadonlyArray<{ name: string; description: string; body: string }> = ${JSON.stringify(prompts, null, 2)};
`;
await fs.writeFile(path.join(root, "src", "core", "skill-prompts.ts"), out);
console.log(`Wrote ${prompts.length} skill prompts to src/core/skill-prompts.ts`);
